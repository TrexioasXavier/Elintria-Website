  // ── Router ───────────────────────────────────────────────────────────────
  function route() {
    var h = decodeURIComponent(location.hash.replace(/^#\/?/, ""));
    document.body.classList.remove("nav-open");
    if (!h) { renderHome(); markActive(""); document.title = "Scripting Documentation"; return; }
    var parts = h.split("/"), slug = parts[0], anchor = parts.slice(1).join("/");
    var o = bySlug[slug];
    if (!o) {
      var lower = slug.toLowerCase();
      o = D.types.filter(function (t) { return t.name.toLowerCase() === lower || t.slug.toLowerCase() === lower; })[0];
    }
    if (!o) {
      article.innerHTML = '<h1>Not found</h1><p>There is no page called <code>' + esc(slug) + '</code>. Try the search bar above.</p>';
      toc.innerHTML = ""; return;
    }
    if (o.kind === "page") renderPage(o); else renderType(o, anchor);
    markActive(o.slug);
    document.title = (o.title || o.name) + " | Scripting Documentation";
  }

